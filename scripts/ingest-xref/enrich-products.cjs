/* Turn a web-enrichment workflow's output into a searchable catalog product tier (ExternalProductEntry[]).
   Each result is self-describing (carries part + brand), so it is robust to failed-agent array shifts.
   Only `found` results with real detail are kept; specs are verified name/value pairs from the agent.
   Run: node enrich-products.cjs <workflow-output-file> <out.ts> <CONST_NAME> <export-comment> */
const fs = require("fs");
const [, , OUTFILE, OUT_TS, CONST, COMMENT] = process.argv;
const clean = (s) => String(s == null ? "" : s).replace(/\s+/g, " ").trim();
const norm = (s) => clean(s).toUpperCase().replace(/[^A-Z0-9]/g, "");

// extract the {results:[...]} object from one or more (comma-separated) workflow output files + merge
function extractResults(file) {
  const raw = fs.readFileSync(file, "utf8");
  const p = raw.indexOf('"results"');
  if (p < 0) return [];
  let s0 = raw.lastIndexOf("{", p);
  let depth = 0, end = -1, inStr = false, esc = false;
  for (let k = s0; k < raw.length; k++) { const c = raw[k]; if (inStr) { if (esc) esc = false; else if (c === "\\") esc = true; else if (c === '"') inStr = false; continue; } if (c === '"') inStr = true; else if (c === "{") depth++; else if (c === "}") { depth--; if (depth === 0) { end = k + 1; break; } } }
  return JSON.parse(raw.slice(s0, end)).results || [];
}
let allResults = OUTFILE.split(",").flatMap((f) => extractResults(f.trim()));
// optional brand filter (ENRICH_KEEP=hub | nonhub) — lets one combined workflow output feed two tiers
const isHub = (b) => /hubbell|wiegmann|burndy|killark|bryant|kellems|taymac|raco|pcore|chance|anderson/i.test(String(b || ""));
const KEEP = process.env.ENRICH_KEEP || "";
if (KEEP === "hub") allResults = allResults.filter((r) => isHub(r.brand));
else if (KEEP === "nonhub") allResults = allResults.filter((r) => !isHub(r.brand));
const obj = { results: allResults };

// map the agent's coarse category to a valid ProductCategory (electrical | datacom)
const DATACOM = /datacom|network|cat ?[56]|fiber|coax|\brf\b|camera|nvr|patch|ethernet|telecom|av\b|audio|video/i;
const catFor = (r) => (DATACOM.test(`${r.category} ${r.productType}`) ? "datacom" : "electrical");

const seen = new Set(); const out = [];
// append mode: keep everything already in the tier file, dedupe new results against it
if (fs.existsSync(OUT_TS)) {
  const ex = fs.readFileSync(OUT_TS, "utf8");
  const a = ex.indexOf("= ["), b = ex.lastIndexOf("];");
  if (a >= 0 && b > a) { try { for (const e of JSON.parse(ex.slice(a + 2, b + 1))) { const k = norm(e.mpn); if (k && !seen.has(k)) { seen.add(k); out.push(e); } } } catch { /* regenerate from scratch */ } }
}
const preexisting = out.length;
for (const r of (obj.results || [])) {
  if (!r.found) continue;
  const part = clean(r.part); if (!part) continue;
  const k = norm(part); if (!k || seen.has(k)) continue; seen.add(k);
  const brand = clean(r.brand) || "Unknown";
  const specs = [{ name: "Manufacturer", value: brand, isNonNeg: true }];
  if (clean(r.productType)) specs.push({ name: "Product Type", value: clean(r.productType) });
  for (const s of (r.keySpecs || [])) { const n = clean(s.name), v = clean(s.value); if (n && v && specs.length < 10) specs.push({ name: n, value: v }); }
  // need at least one real attribute beyond the manufacturer to count as "enriched"
  if (specs.length < 2) continue;
  const desc = clean(r.description) || `${brand} ${clean(r.productType) || part}`;
  const entry = {
    mpn: part, brand,
    name: `${brand} ${clean(r.productType) || part} ${part}`.replace(/\s+/g, " ").slice(0, 90),
    category: catFor(r), subcategory: (clean(r.productType) || "Catalog Items").slice(0, 40),
    description: desc.slice(0, 220), specs, verifiedAt: "2026-06-26",
  };
  const url = clean(r.datasheetUrl); if (/^https?:\/\//.test(url)) entry.specSheetUrl = url;
  out.push(entry);
}
const ts = `import type { ExternalProductEntry } from "@/lib/catalog/external-products";

/**
 * ${COMMENT}
 * Web-enriched ${new Date().getUTCFullYear()} with VERIFIED specs from manufacturer sources — only
 * fields confirmed on an authoritative page are kept; unverifiable parts are dropped (not faked).
 * Generated by scripts/ingest-xref/enrich-products.cjs.
 */
export const ${CONST}: ExternalProductEntry[] = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync(OUT_TS, ts);
const withUrl = out.filter((e) => e.specSheetUrl).length;
console.log(`Wrote ${OUT_TS}: ${out.length} enriched products (+${out.length - preexisting} new this run, ${(obj.results || []).length} researched), ${withUrl} with datasheet URLs, avg specs ${(out.reduce((s, e) => s + e.specs.length, 0) / (out.length || 1)).toFixed(1)}`);

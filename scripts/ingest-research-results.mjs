// Transform verified-data research workflow output into the typed data files.
// Usage: node scripts/ingest-research-results.mjs <result.json> [verifiedAt]
// Decodes HTML entities, dedupes brands/aliases and unordered pairs, and emits
// data/real/brand-hierarchy.ts + data/real/verified-crosses.ts.
import fs from "node:fs";

const [, , resultPath, verifiedAt = new Date().toISOString().slice(0, 10)] = process.argv;
if (!resultPath) {
  console.error("usage: node scripts/ingest-research-results.mjs <result.json> [verifiedAt]");
  process.exit(1);
}
const r = JSON.parse(fs.readFileSync(resultPath, "utf8"));
const dec = (s) => (typeof s === "string" ? s.replace(/&amp;/g, "&") : s);

// ── Hierarchy ────────────────────────────────────────────────────────────────
const hier = r.hierarchy.map((e) => ({
  brand: dec(e.brand),
  ...(e.aliases && e.aliases.length ? { aliases: e.aliases.map(dec) } : {}),
  ...(e.subBrand ? { subBrand: dec(e.subBrand) } : {}),
  ...(e.division ? { division: dec(e.division) } : {}),
  parentCompany: dec(e.parentCompany),
  sourceUrl: e.sourceUrl,
  ...(e.wescoBrandUrl ? { wescoBrandUrl: e.wescoBrandUrl } : {}),
  verifiedAt,
}));
const seen = new Set();
const cleanHier = [];
for (const e of hier) {
  const k = e.brand.toLowerCase();
  if (seen.has(k)) {
    console.log("DROP duplicate brand:", e.brand);
    continue;
  }
  seen.add(k);
  if (e.aliases) {
    e.aliases = e.aliases.filter((a) => {
      const ak = a.toLowerCase();
      if (seen.has(ak) || ak === k) return false;
      seen.add(ak);
      return true;
    });
    if (!e.aliases.length) delete e.aliases;
  }
  cleanHier.push(e);
}

// ── Crosses ──────────────────────────────────────────────────────────────────
const crosses = r.crosses.map((c) => ({
  aBrand: dec(c.aBrand),
  aMpn: c.aMpn,
  bBrand: dec(c.bBrand),
  bMpn: c.bMpn,
  relation: c.relation,
  sourceKind: c.sourceKind,
  sourceUrl: c.sourceUrl,
  ...(c.notes ? { notes: dec(c.notes) } : {}),
  verifiedAt,
}));
const pairKey = (c) => {
  const a = c.aMpn.toUpperCase().replace(/[^A-Z0-9]/g, "");
  const b = c.bMpn.toUpperCase().replace(/[^A-Z0-9]/g, "");
  return a < b ? `${a}|${b}` : `${b}|${a}`;
};
const cseen = new Set();
const cleanCross = [];
for (const c of crosses) {
  const k = pairKey(c);
  if (cseen.has(k)) {
    console.log("DROP duplicate pair:", c.aMpn, "<->", c.bMpn);
    continue;
  }
  cseen.add(k);
  cleanCross.push(c);
}

// ── Emit ─────────────────────────────────────────────────────────────────────
const hierTs = `import type { BrandNode } from "@/lib/catalog/brand-hierarchy";

/**
 * Researched brand-hierarchy facts (verified-data research workflow, ${verifiedAt}).
 * Every sourceUrl was retrieved or seen verbatim in search results at research
 * time; relationships without a supporting source were not added.
 * GENERATED by scripts/ingest-research-results.mjs — do not hand-edit
 * relationships without a source.
 */
export const BRAND_HIERARCHY_ENTRIES: BrandNode[] = ${JSON.stringify(cleanHier, null, 1)};
`;
const crossTs = `import type { VerifiedCrossEntry } from "@/lib/catalog/verified-crosses";

/**
 * Source-backed cross-reference pairs (verified-data research workflow, ${verifiedAt}).
 * Every pair cites the official cross-reference tool, datasheet, or published
 * cross table that states it — link-verified at research time. Qualifiers from
 * the source (UL-classification limits, coil/aux differences) are preserved in
 * notes and MUST be surfaced with the recommendation.
 * GENERATED by scripts/ingest-research-results.mjs — do not add pairs without
 * a citable source.
 */
export const VERIFIED_CROSS_ENTRIES: VerifiedCrossEntry[] = ${JSON.stringify(cleanCross, null, 1)};
`;
fs.writeFileSync("data/real/brand-hierarchy.ts", hierTs);
fs.writeFileSync("data/real/verified-crosses.ts", crossTs);
const urls = [...new Set([...cleanHier.map((e) => e.sourceUrl), ...cleanCross.map((c) => c.sourceUrl)])];
fs.writeFileSync("data/real/research/source-urls.txt", urls.join("\n") + "\n");
console.log("hierarchy:", cleanHier.length, "| crosses:", cleanCross.length, "| unique source urls:", urls.length);
